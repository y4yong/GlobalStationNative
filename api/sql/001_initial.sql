CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('VIEWER', 'CREATOR', 'ADVERTISER', 'ADMIN') NOT NULL,
  status ENUM('ACTIVE', 'SUSPENDED') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dramas (
  id VARCHAR(64) PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL,
  genre VARCHAR(100) NOT NULL,
  rating VARCHAR(20) NOT NULL,
  badge ENUM('VIP', 'FREE') NOT NULL,
  progress DECIMAL(4, 3),
  time_left VARCHAR(100),
  tag VARCHAR(100),
  description TEXT NOT NULL,
  episodes JSON NOT NULL,
  status ENUM('DRAFT', 'IN_REVIEW', 'PUBLISHED', 'REJECTED') NOT NULL DEFAULT 'PUBLISHED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX dramas_status_created_at_idx ON dramas (status, created_at DESC);
